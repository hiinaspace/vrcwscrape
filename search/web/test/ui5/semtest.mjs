// Real-click check of the semantic toggle. node test/ui5/semtest.mjs <base> <chromium|firefox> [q]
import { launch } from "./launch.mjs";
const base = process.argv[2] ?? "http://localhost:5199/", kind = process.argv[3] ?? "chromium", q = process.argv[4] ?? "";
const b = await launch(kind);
const p = await (await b.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
const dialogs = [], errs = [];
p.on("dialog", async (d) => { dialogs.push(d.message()); await d.dismiss(); });
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(base + (q ? "?q=" + encodeURIComponent(q) : ""));
await p.waitForSelector("[data-testid=result-item]");
const T = (id) => p.locator("[data-testid=" + id + "]");
const out = { kind, q };
out.t0 = await T("sem-toggle").getAttribute("aria-checked");
await T("sem-toggle").click();
out.confirmVisible = await T("sem-enable").isVisible();
out.enableLabel = (await T("sem-enable").textContent()).trim();
await T("sem-enable").click();
await p.waitForTimeout(150);
out.progressVisible = await p.locator(".sem-loading").isVisible();
await p.waitForFunction(() => document.querySelector("[data-testid=sem-toggle]")?.getAttribute("aria-checked") === "true", null, { timeout: 60000 });
out.on = await T("sem-toggle").getAttribute("aria-checked");
out.note = await p.textContent(".sem-note");
out.semSectionVisible = await p.locator("#semantic").isVisible();
out.hint = (await p.textContent("#sem-hint")).trim();
await p.screenshot({ path: "/work/tmp-ui5/ui5shots/" + kind + "-sem-on-empty.png" });
await p.fill("#q", "quiet forest cabin to relax");
await p.waitForFunction(() => document.querySelectorAll("[data-testid=semantic-item]").length > 0, null, { timeout: 15000 });
out.semItems = await T("semantic-item").count();
out.firstSem = (await T("semantic-item").first().locator(".title").textContent());
await p.screenshot({ path: "/work/tmp-ui5/ui5shots/" + kind + "-sem-on-query.png" });
await p.reload(); await p.waitForFunction(() => document.querySelector("[data-testid=sem-toggle]")?.getAttribute("aria-checked") === "true", null, { timeout: 60000 });
out.rememberedAfterReload = true;
await T("sem-toggle").click();
out.offAfter = await T("sem-toggle").getAttribute("aria-checked");
out.sectionAfterOff = await p.locator("#semantic").isVisible();
out.dialogs = dialogs; out.errs = errs;
console.log(JSON.stringify(out, null, 1));
await b.close();
